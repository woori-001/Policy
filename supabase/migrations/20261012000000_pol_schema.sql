-- ============================================================================
-- 상부정책 관리 (Policy) — Supabase 저장소
--
-- 같은 프로젝트에 다른 앱 테이블(carriers, policies, settings, admins …)이 있어서
-- 이 앱 테이블은 모두 pol_ 로 시작합니다. 다른 앱 테이블은 건드리지 않습니다.
--
-- 접근 방식
--   · 화면(브라우저)은 테이블에 직접 접근하지 않습니다.
--   · 모든 읽기/쓰기는 Edge Function "policy-api" 가 서버 쪽에서 합니다.
--     (구글 로그인 → 이메일이 pol_members 명단에 있는지 → 권한 확인 → DB)
--   · 그래서 RLS 를 켜고 정책(policy)은 하나도 두지 않습니다 = anon/authenticated 는 전부 거부.
--     Edge Function 은 DB 연결(SUPABASE_DB_URL, postgres 역할)로 들어와 RLS 영향을 받지 않습니다.
--
-- 시각은 예전 시트와 같은 'YYYY-MM-DD HH:mm' (한국 시간) 글자로 둡니다 — 화면 로직이 그대로 씁니다.
-- ============================================================================

-- 명단 (예전 ALLOW 시트)
create table if not exists public.pol_members (
  email   text primary key check (email = lower(email) and email <> ''),
  name    text not null default '',
  role    text not null check (role in ('관리자', '편집담당자', '열람전용')),
  ord     integer not null default 0
);
comment on table public.pol_members is '상부정책 관리 · 명단 (구글 로그인 이메일 → 권한)';

-- 단일 값 설정 (tree · tree_prev · pt_open · pt_mix)
create table if not exists public.pol_kv (
  key        text primary key,
  value      jsonb,
  updated_at timestamptz not null default now()
);
comment on table public.pol_kv is '상부정책 관리 · 통신사/중분류 구조(tree) · 협력점 정책 설정(pt_open, pt_mix)';

-- 상부정책 현재본 (예전 POLICY)
create table if not exists public.pol_policy (
  sub_id    text primary key,
  rev       integer not null default 0,
  last_by   text not null default '',
  saved_at  text not null default '',
  eff_at    text not null default '',
  body      jsonb not null default '{}'::jsonb
);
comment on table public.pol_policy is '상부정책 관리 · 중분류별 현재(마지막 저장) 정책';

-- 임시저장 (예전 DRAFT)
create table if not exists public.pol_draft (
  sub_id    text primary key,
  base_rev  integer not null default 0,
  author    text not null default '',
  at        text not null default '',
  body      jsonb not null default '{}'::jsonb
);
comment on table public.pol_draft is '상부정책 관리 · 중분류별 임시저장(초안)';

-- 상부정책 이력 (예전 HIST). id = 예전 시트 행 번호를 그대로 옮겨 씁니다
create table if not exists public.pol_hist (
  id        bigint generated by default as identity primary key,
  sub_id    text not null,
  eff_at    text not null,
  saved_at  text not null,
  author    text not null default '',
  kind      text not null default '단가',          -- '단가' | '기타' | '단가@고친사람@고친시각'
  body      jsonb not null default '{}'::jsonb
);
create index if not exists pol_hist_sub_idx on public.pol_hist (sub_id, eff_at, saved_at);
comment on table public.pol_hist is '상부정책 관리 · 저장할 때마다 남는 정책 이력';

-- 휴지통 (예전 휴지통 · PSHEET_휴지통). 지우거나 덮어쓴 것을 통째로 남깁니다
create table if not exists public.pol_trash (
  id          bigint generated by default as identity primary key,
  kind        text not null,                       -- '이력' | '이력 정정 전' | '틀' | '발행' | '덮어쓴 발행' | …
  ref         text not null default '',            -- sub_id 또는 gid
  deleted_at  text not null default '',
  deleted_by  text not null default '',
  data        jsonb
);
comment on table public.pol_trash is '상부정책 관리 · 지운/덮어쓴 기록 보관';

-- 등급 차감표 (예전 GRADE) — 한 줄
create table if not exists public.pol_grades (
  id      integer primary key default 1 check (id = 1),
  rev     integer not null default 0,
  author  text not null default '',
  at      text not null default '',
  cfg     jsonb
);
comment on table public.pol_grades is '상부정책 관리 · 협력점 정책 등급 차감표 (현재)';

create table if not exists public.pol_grades_hist (
  id      bigint generated by default as identity primary key,
  at      text not null default '',
  author  text not null default '',
  what    text not null default '',
  cfg     jsonb
);
comment on table public.pol_grades_hist is '상부정책 관리 · 등급 차감표 저장 이력';

-- 협력점 정책지 틀 (예전 PSHEET)
create table if not exists public.pol_psheet (
  gid     text primary key,
  rev     integer not null default 0,
  author  text not null default '',
  at      text not null default '',
  tpl     jsonb
);
comment on table public.pol_psheet is '상부정책 관리 · 협력점 정책지 틀(편집 현재본)';

-- 협력점 정책지 발행 이력 (예전 PSHEET_이력)
create table if not exists public.pol_psheet_hist (
  id      bigint generated by default as identity primary key,
  gid     text not null,
  at      text not null default '',
  author  text not null default '',
  eff     text not null default '',
  snap    jsonb
);
create index if not exists pol_psheet_hist_gid_idx on public.pol_psheet_hist (gid, id desc);
comment on table public.pol_psheet_hist is '상부정책 관리 · 협력점 정책지 발행본';

-- My Page 메모 (예전 MEMO)
create table if not exists public.pol_memo (
  id      text primary key,
  email   text not null,
  author  text not null default '',
  shared  boolean not null default false,
  cat     text not null check (cat in ('멘트', '할일', '업체')),
  title   text not null default '',
  body    text not null default '',
  at      text not null default '',
  done    boolean not null default false,
  cids    text[] not null default '{}'
);
create index if not exists pol_memo_email_idx on public.pol_memo (email);
comment on table public.pol_memo is '상부정책 관리 · My Page 메모';

-- 비밀번호 해시 (등급 차감 편집 비밀번호) — 화면으로 절대 안 나감
create table if not exists public.pol_secret (
  key    text primary key,                         -- 'pw:<통신사 id>' | 'pw:common'
  value  text not null
);
comment on table public.pol_secret is '상부정책 관리 · 비밀번호 해시 (Edge Function 만 읽음)';

-- 비밀번호 틀린 횟수 (10분에 8번까지)
create table if not exists public.pol_pwfail (
  email  text primary key,
  n      integer not null default 0,
  until  timestamptz not null default now()
);
comment on table public.pol_pwfail is '상부정책 관리 · 비밀번호 틀린 횟수 (잠시 잠금용)';

-- ── RLS: 켜고, 정책은 두지 않음 = 브라우저(anon/authenticated)에서는 전부 거부 ──
do $$
declare t text;
begin
  foreach t in array array['pol_members','pol_kv','pol_policy','pol_draft','pol_hist','pol_trash',
                           'pol_grades','pol_grades_hist','pol_psheet','pol_psheet_hist','pol_memo',
                           'pol_secret','pol_pwfail']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
  end loop;
end $$;
